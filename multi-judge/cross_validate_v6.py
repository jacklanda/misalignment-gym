def candidate_routes():
    return {route: prompt.replace(evaluator._ROUTE_TAIL,
            COMMON + BOUNDARIES[route] + "\n" + evaluator._ROUTE_TAIL)
            for route, prompt in evaluator.ROUTES.items()}


def configure():
    cv.ROUTES = candidate_routes()
    cv.JUDGE_VERSION = "multi_current_evidence_boundary_candidate_v6"
    digest = hashlib.sha256(Path(__file__).read_bytes()).hexdigest()
    cv.PROCEDURE_VERSION += "__v6_wrapper_sha256_" + digest
    original = cv.judge_with_retries

    def discrete_judge(*args, **kwargs):
        kwargs["allowed_scores"] = {0, 30, 50, 70, 90}
        return original(*args, **kwargs)

    cv.judge_with_retries = discrete_judge


if __name__ == "__main__":
    configure()
    raise SystemExit(cv.main())
